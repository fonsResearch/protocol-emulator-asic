#!/usr/bin/env python3
"""Report of the check-witness obligation: log/witness_v2_table.md and log/witness_v2.csv from
$WOUT/<name>.txt (prove_one rows), <name>.replay.txt and list.txt.

Per check: result (WITNESSED = FAIL with the counterexample replayed in cyclesim; DEAD = PASS, the
check can never be the first verdict; OPEN = undecided / timeout), depth, wall time, and the
cross-check by the reference interpreter (Pemu_monitor_v1.Interp, run by replay_cex on the
monitor inputs of the trace): 'agrees' when it fires the same role and code in the trace's last
frame, with the statement it names.

Checks the formal cover leaves OPEN are looked up in $WSEARCH/<pkg>_<role><code>.txt (directed
witness search, mutants_v2.exe wsearch): a hit whose chip-RTL run confirms the verdict becomes
WITNESSED with method 'directed' (the Psim verdict is the reference interpreter's, so the
interpreter column reads 'agrees (Psim)'; the chip column is the v2 RTL's first verdict)."""
import csv
import os
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[3]
W = root / os.environ.get("WOUT", "formal/work/mut_v2/witness3")
WS = root / os.environ.get("WSEARCH", "formal/work/mut_v2/wsearch")
rows = []
for line in (W / "list.txt").read_text().splitlines():
    name, pkg, role, code, stmts = line.split(" ", 4)
    r = {"name": name, "pkg": pkg, "role": role, "code": code, "statements": stmts}
    f = W / f"{name}.txt"
    if not f.exists():
        r.update(result="missing", depth="", wall="", replay="", interp="", site="", method="", witness="", chip="")
        rows.append(r)
        continue
    p = [x.strip() for x in f.read_text().split("|")]
    res, depth, wall, replay = (p[4], p[5], p[7], p[8]) if len(p) > 8 else ("ERROR", "", "", "")
    r["depth"], r["wall"], r["replay"] = depth, wall, replay
    if res == "FAIL" and replay.startswith("replay ok"):
        r["result"] = "WITNESSED"
    elif res == "PASS":
        r["result"] = "DEAD"
    elif res in ("UNDECIDED", "TIMEOUT"):
        r["result"] = "OPEN"
    else:
        r["result"] = "ERROR"
    r["interp"], r["site"] = "", ""
    rp = W / f"{name}.replay.txt"
    if r["result"] == "WITNESSED" and rp.exists():
        txt = rp.read_text()
        m = re.search(r"bad first rises at frame (\d+)", txt)
        last = int(m.group(1)) if m else None
        want = ("fail" if role == "F" else "blame") + " " + code
        hits = re.findall(r"# interp frame (\d+): (fail|blame) ([0-9A-F]{2}) at (\S+ #\d+)", txt)
        same = [h for h in hits if int(h[0]) == last and f"{h[1]} {h[2]}" == want]
        r["interp"] = "agrees" if same else ("differs: " + ", ".join(f"{h[1]} {h[2]}@{h[0]}" for h in hits[:3]) if hits else "no decode")
        r["site"] = same[0][3] if same else ""
    r["method"], r["witness"] = ("formal" if r["result"] == "WITNESSED" else ""), ""
    if r["result"] == "OPEN":
        ws = WS / f"{pkg}_{role}{code}.txt"
        last = ws.read_text().strip().splitlines()[-1] if ws.exists() else ""
        m = re.match(r"WSEARCH \S+ \S+ FOUND \[(.*)\] psim first verdict at (\d+); chip (CONFIRMED|NOT CONFIRMED) \(first fail (\S+), first blame (\S+)\)", last)
        if m and m.group(3) == "CONFIRMED":
            r["result"], r["method"] = "WITNESSED", "directed"
            r["witness"] = f"{m.group(1)} @ cycle {m.group(2)}"
            r["interp"], r["site"] = "agrees (Psim)", ""
            r["chip"] = f"fail {m.group(4)} blame {m.group(5)}"
        elif last:
            r["witness"] = last.split(" ", 3)[-1]
    r.setdefault("chip", "")
    rows.append(r)

with open(root / "log" / "witness_v2.csv", "w", newline="") as fh:
    w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
    w.writeheader()
    w.writerows(rows)

out = ["# Check-witness results (generated by formal/mutation/v2/witness_report.py)\n"]
pk = []
for r in rows:
    if r["pkg"] not in pk:
        pk.append(r["pkg"])
out.append("| package | checks | witnessed (formal + directed) | dead | open | error | interpreter agrees |")
out.append("|---|---|---|---|---|---|---|")
tot = {"n": 0, "WITNESSED": 0, "DEAD": 0, "OPEN": 0, "ERROR": 0, "agree": 0, "formal": 0, "directed": 0}
for p in pk:
    g = [r for r in rows if r["pkg"] == p]
    c = {k: sum(1 for r in g if r["result"] == k) for k in ("WITNESSED", "DEAD", "OPEN", "ERROR")}
    a = sum(1 for r in g if r["interp"].startswith("agrees"))
    nf = sum(1 for r in g if r["method"] == "formal"); nd = sum(1 for r in g if r["method"] == "directed")
    out.append(f"| {p} | {len(g)} | {c['WITNESSED']} ({nf} + {nd}) | {c['DEAD']} | {c['OPEN']} | {c['ERROR']} | {a}/{c['WITNESSED']} |")
    tot["n"] += len(g); tot["agree"] += a; tot["formal"] += nf; tot["directed"] += nd
    for k in c:
        tot[k] += c[k]
out.append(f"| all | {tot['n']} | {tot['WITNESSED']} ({tot['formal']} + {tot['directed']}) | {tot['DEAD']} | {tot['OPEN']} | {tot['ERROR']} | {tot['agree']}/{tot['WITNESSED']} |")
out.append("\n| check | role | code | statements | result | method | depth | wall s | interpreter | fired statement | directed witness | chip RTL |")
out.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
for r in rows:
    st = r["statements"] if len(r["statements"]) < 70 else r["statements"][:67] + "..."
    out.append(f"| {r['name']} | {r['role']} | {r['code']} | {st} | {r['result']} | {r['method']} | {r['depth']} | {r['wall']} | {r['interp']} | {r['site']} | {r['witness']} | {r['chip']} |")
(root / "log" / "witness_v2_table.md").write_text("\n".join(out) + "\n")
print(f"{tot['n']} checks: witnessed {tot['WITNESSED']} (formal {tot['formal']}, directed {tot['directed']}), dead {tot['DEAD']}, open {tot['OPEN']}, error {tot['ERROR']}, interpreter agrees {tot['agree']}")
