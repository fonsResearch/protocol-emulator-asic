(* Printed view of a contract (decision Q1, 2026-10-17: the OCaml embedded DSL is the source of
   truth and the text form is a printed view). The view is itself DSL source: it uses the Lang
   combinators where they are exact and constructors elsewhere, so it can be compiled back.
   toolchain/test checks that the printed ROM library compiles to contracts equal (Lang.equal) to
   Rom_lib.v2_inc5 (). Binary operators are always parenthesised. *)
open! Core
module L = Pemu_monitor_v1.Lang

let q s = sprintf "%S" s
let code k = sprintf "0x%02X" k

let check ((r, k) : L.check) =
  match r with
  | Fail -> sprintf "(fail %s)" (code k)
  | Blame -> sprintf "(blame %s)" (code k)
;;

let atom obs (kind : L.kind) delay =
  let f = match kind with Level -> "at" | Rise -> "rise" | Fall -> "fall" | Changed -> "changed" in
  match kind, delay with
  | Level, 0 -> sprintf "(v %s)" (q obs)
  | _, 0 -> sprintf "(%s %s)" f (q obs)
  | _ -> sprintf "(%s ~delay:%d %s)" f delay (q obs)
;;

let rec expr (e : L.expr) =
  match e with
  | True -> "True"
  | False -> "False"
  | Atom { obs; kind; delay } -> atom obs kind delay
  | Reg_bit i -> sprintf "(Reg_bit %d)" i
  | Eq_reg (e, i) -> sprintf "(eq_reg %s %d)" (expr e) i
  | Elapsed_ge { mark; t } -> sprintf "(Elapsed_ge { mark = %d; t = %d })" mark t
  | Not e -> sprintf "(!!%s)" (expr e)
  | And (a, b) -> sprintf "(%s &&& %s)" (expr a) (expr b)
  | Or (a, b) -> sprintf "(%s ||| %s)" (expr a) (expr b)
;;

let when_ (w : L.expr) = match w with True -> "" | w -> sprintf " ~when_:%s" (expr w)

let window (w : L.window) =
  sprintf "(win%s%s %d %d ~else_:%s)"
    (match w.since with None -> "" | Some m -> sprintf " ~since:%d" m)
    (match w.early with None -> "" | Some c -> sprintf " ~early:%s" (check c))
    w.lo w.hi (check w.timeout)
;;

let stream (s : L.stream) = match s with Tx_pop -> "Tx_pop" | Rx_push -> "Rx_push"
let byte b = if b = 0 then "" else sprintf " ~byte:%d" b

let rec stmts ind (l : L.stmt list) =
  match l with
  | [] -> "[]"
  | _ ->
    let pad = String.make ind ' ' in
    "[ "
    ^ String.concat ~sep:("\n" ^ pad ^ "; ") (List.map l ~f:(stmt (ind + 2)))
    ^ "\n" ^ String.make ind ' ' ^ "]"

and stmt ind (s : L.stmt) =
  match s with
  | Await_idle { e; when_ = w } -> sprintf "await_idle%s %s" (when_ w) (expr e)
  | Await { e; when_ = w; w = x } -> sprintf "await%s %s %s" (when_ w) (expr e) (window x)
  | Hold_for { r; when_ = w; n; check = c } -> sprintf "hold%s %s ~for_:%d ~else_:%s" (when_ w) (expr r) n (check c)
  | Hold_until { r; when_ = w; e; w = x } -> sprintf "hold_until%s %s %s %s" (when_ w) (expr r) (expr e) (window x)
  | Skip n -> sprintf "skip %d" n
  | Take { s; byte = b; w = None } -> sprintf "take_idle%s %s" (byte b) (stream s)
  | Take { s; byte = b; w = Some x } -> sprintf "take%s %s %s" (byte b) (stream s) (window x)
  | Expect { r; when_ = w; check = c } -> sprintf "expect%s %s ~else_:%s" (when_ w) (expr r) (check c)
  | Sample { bit; e } -> sprintf "sample %d %s" bit (expr e)
  | Match { check = c } -> sprintf "match_rx ~else_:%s" (check c)
  | Mark a -> sprintf "mark %d" a
  | Raise c -> sprintf "raise_ %s" (check c)
  | If (b, t, e) -> sprintf "if_ %s\n%s%s\n%s%s" (expr b) (String.make (ind + 2) ' ') (stmts (ind + 2) t) (String.make (ind + 2) ' ') (stmts (ind + 2) e)
  | Loop b -> sprintf "loop\n%s%s" (String.make (ind + 2) ' ') (stmts (ind + 2) b)
  | Repeat (n, b) -> sprintf "repeat %d\n%s%s" n (String.make (ind + 2) ' ') (stmts (ind + 2) b)
  | Guard { g; body; handler } ->
    sprintf "guard %s\n%s%s\n%s~on:%s" (expr g) (String.make (ind + 2) ' ') (stmts (ind + 2) body) (String.make (ind + 2) ' ')
      (stmts (ind + 6) handler)
;;

let source (s : L.source) =
  match s with
  | Uo k -> sprintf "Uo %d" k
  | Uio_out k -> sprintf "Uio_out %d" k
  | Uio_oe k -> sprintf "Uio_oe %d" k
  | Ui k -> sprintf "Ui %d" k
  | Uio_in k -> sprintf "Uio_in %d" k
  | Drive k -> sprintf "Drive %d" k
  | Tx_pop_ev -> "Tx_pop_ev"
  | Rx_push_ev -> "Rx_push_ev"
;;

(* the contract as a DSL expression of type Lang.t (needs [open Pemu_monitor_v1.Lang]) *)
let contract (c : L.t) =
  let obs = String.concat ~sep:"; " (List.map c.observables ~f:(fun (n, s) -> sprintf "%s, %s" (q n) (source s))) in
  let w (x : L.watcher) = sprintf "watcher %s ~base:%s\n      %s" (q x.wname) (code x.base) (stmts 6 x.body) in
  sprintf "{ name = %s\n  ; observables = [ %s ]\n  ; watchers =\n      [ %s\n      ]\n  }" (q c.name) obs
    (String.concat ~sep:"\n      ; " (List.map c.watchers ~f:w))
;;

(* a compilable module: [let contracts = [ ... ]] *)
let library_module (cs : L.t list) =
  "(* generated by toolchain/bin/pemu_cc.exe print-library: printed view of the shipped ROM\n   library; do not edit *)\nopen! Core\nopen Pemu_monitor_v1.Lang\n\nlet contracts : t list =\n  [ "
  ^ String.concat ~sep:"\n  ; " (List.map cs ~f:contract)
  ^ "\n  ]\n"
;;
